num <- function(x, d = 3) {
  s <- formatC(abs(x), format = "f", digits = d)
  ifelse(x < 0 & as.numeric(s) > 0, paste0("$-", s, "$"), s)
}
es  <- function(e, se, d = 3) paste0(num(e, d), " (", formatC(se, format = "f", digits = d), ")")
pv  <- function(p) ifelse(p < .001, "$< .001$", sub("^0", "", sprintf("%.3f", p)))
psci <- function(p) sapply(p, function(x) {
  if (x >= .001) return(sub("^0", "", sprintf("%.3f", x)))
  if (x <= 0) return("$< 10^{-300}$")
  e <- floor(log10(x)); m <- round(x / 10^e, 1)
  if (m >= 10) { m <- m / 10; e <- e + 1 }
  sprintf("$%.1f \\times 10^{%d}$", m, e)
})
W2  <- function(w) sprintf("%.2f", w)
Nm  <- function(n) gsub(",", "{,}", N(n), fixed = TRUE)          # counts inside $...$
