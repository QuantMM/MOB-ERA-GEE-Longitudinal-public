# ---------------------------------------------------------------------------
# 23_supplementary_tables.R
#
# Builds every table of the Supplementary Results document directly from the
# analysis data and the saved partitioning fits, so no number is transcribed
# by hand. Everything uses the Flag-determinate samples reported in the paper
# (balanced 24,948 persons; all-available 29,169 persons) and the fixed
# reference age of 62.15 years used in Analysis/15-22.
#
#   Table S1   Primary longitudinal model, full sample (all coefficients,
#              joint tests, model-implied values at three ages)
#   Table S2   Observed means by assessment; equal-change check by domain
#   Table S3   Immigrant vs non-immigrant, elementwise (CI, Holm, MDD)
#   Table S4   Settlement duration: primary three-group and finer bands
#   Table S5   Root-node parameter-instability tests, all 15 trees
#   Table S6   Splits of every tree (alpha = .05)
#   Table S7   Terminal-node estimates and global age coefficients
#   Table S8   Sex and racialization contrasts within migration groups
#   Table S9   Between-group comparison of those contrasts
#   Table S10  All-available person-wave sensitivity analysis
#   (Table S11, the alpha = .01 comparison, is static LaTeX in the document.)
#
# SMALL CELLS. No count below 6 is written. White stratum sizes are never
# written (they would disclose missing racialization counts). Every depth-1
# node whose defining characteristic has a published total is checked for a
# back-calculable difference of 1-5; the script stops if one is found.
#
# Run from the project root:
#     Rscript Analysis/23_supplementary_tables.R
# Writes (local only until CLSA review):
#     Draft/manuscript_clsa_review_package/supplementary_results.tex (tables S1-S10
#       embedded between its GENERATED TABLES markers; the rest of the file is kept)
