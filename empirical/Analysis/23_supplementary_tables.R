tree_info <- function(fit, dd) {
  tr <- fit$tree
  stopifnot(length(fit$node) == nrow(dd))
  pid <- function(ids) length(unique(dd$id[!is.na(fit$node) & fit$node %in% ids]))
  paths <- list()
  walk <- function(nd, conds) {
    paths[[as.character(id_node(nd))]] <<- conds
    if (is.terminal(nd)) return(invisible())
    sp <- split_node(nd); vn <- names(tr$data)[varid_split(sp)]; zz <- tr$data[[vn]]; idx <- index_split(sp)
    kd <- kids_node(nd)
    for (k in seq_along(kd)) { cc <- conds; cc[[vn]] <- levels(zz)[which(idx == k)]; walk(kd[[k]], cc) }
  }
  walk(node_party(tr), list())
  path_lab <- function(id) { cc <- paths[[as.character(id)]]
    if (!length(cc)) return("All")
    paste(sapply(names(cc), function(v) lev_lab(v, cc[[v]], levels(tr$data[[v]]))), collapse = "; ") }
  root <- nodeapply(tr, 1, function(n) info_node(n))[[1]]
  inner <- setdiff(nodeids(tr), nodeids(tr, terminal = TRUE))
  splits <- lapply(inner, function(i) {
    nd <- nodeapply(tr, i, identity)[[1]]; sp <- split_node(nd); vn <- names(tr$data)[varid_split(sp)]
    zz <- tr$data[[vn]]; idx <- index_split(sp); ti <- info_node(nd)
    list(id = i, path = path_lab(i), n = pid(nodeids(tr, from = i, terminal = TRUE)), var = vn,
         left = lev_lab(vn, levels(zz)[which(idx == 1)], levels(zz)), right = lev_lab(vn, levels(zz)[which(idx == 2)], levels(zz)),
         p = ti$test["p.value", vn], stat = ti$test["statistic", vn])
  })
  # terminal-node estimates on the age-adjusted outcomes
  Ac <- dd$z_age - AGE_C
  off <- sapply(seq_along(Y), function(q) fit$gamma["age", q] * Ac + fit$gamma["age_time", q] * dd$X_time * Ac)
  term <- lapply(nodeids(tr, terminal = TRUE), function(i) {
    ix <- which(!is.na(fit$node) & fit$node == i)
    m <- era_gee_components(as.matrix(dd[ix, Y]) - off[ix, , drop = FALSE], cbind(beta1 = 1, beta2 = dd$X_time[ix]), dd$id[ix])
    list(id = i, path = path_lab(i), n = length(unique(dd$id[ix])), B = m$B)
  })
  list(root = root, root_n = pid(nodeids(tr, terminal = TRUE)), splits = splits, term = term,
       gamma = fit$gamma, width = width(tr), paths = paths, conv = fit$converged, tr = tr,
       node = fit$node, ids = dd$id)
}
