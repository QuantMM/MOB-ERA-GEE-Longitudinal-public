# fb - fa for two independent fits
pair <- function(fa, fb) {
  nm <- rownames(fa$V); dif <- fb$theta - fa$theta; Vd <- fa$V + fb$V; se <- sqrt(diag(Vd))
  wald <- function(j) { j <- match(j, nm)
    W <- as.numeric(t(dif[j]) %*% solve(Vd[j, j, drop = FALSE]) %*% dif[j])
    c(W = W, df = length(j), p = pchisq(W, length(j), lower.tail = FALSE)) }
  names(dif) <- names(se) <- nm
  list(dif = dif, se = se, p = 2 * pnorm(-abs(dif / se)), mdd = 2.8 * se,
       block = sapply(CMP, function(k) wald(nm_of(k))), all = wald(nm))
}
# omnibus equality across K independent groups (all contrasts against group 1)
omnibus <- function(fits, comps) {
  ref <- fits[[1]]; oth <- fits[-1]; nm <- rownames(ref$V); j <- match(unlist(lapply(comps, nm_of)), nm)
  d  <- unlist(lapply(oth, function(f) (f$theta - ref$theta)[j]))
  k  <- length(oth); m <- length(j)
  V  <- matrix(0, k * m, k * m)
  for (a in seq_len(k)) for (b in seq_len(k)) {
    blk <- ref$V[j, j]; if (a == b) blk <- blk + oth[[a]]$V[j, j]
    V[(a - 1) * m + 1:m, (b - 1) * m + 1:m] <- blk
  }
  W <- as.numeric(t(d) %*% solve(V) %*% d)
  c(W = W, df = k * m, p = pchisq(W, k * m, lower.tail = FALSE))
}

